export function findGlossary(term: string): { term: string; meaning: string }[] {
  const q = term.trim().toLowerCase();
  if (!q) return [];
  return Object.entries(GLOSSARY)
    .filter(([k, v]) => k.toLowerCase().includes(q) || q.includes(k.split(" ")[0].toLowerCase()) || v.includes(q))
    .slice(0, 5)
    .map(([k, v]) => ({ term: k, meaning: v }));
}
