/**
 * خواندن پیام خطای یک پاسخ فرم.
 *
 * ⚠️ چرا این تابع لازم است: سایت‌ها پشت CDN هستند و CDN بدنه‌ی پاسخ‌های ۴xx
 * را با صفحه‌ی خطای HTML خودش عوض می‌کند. سرور JSON درست برمی‌گرداند
 * (روی خودِ اوریجین تست شد) ولی چیزی که به مرورگر می‌رسد HTML است، پس
 * `res.json()` استثنا می‌دهد و کاربر به‌جای «نام خود را بنویسید» پیام
 * «ارتباط با سرور برقرار نشد» می‌بیند.
 *
 * پس اول JSON را امتحان می‌کنیم و اگر نشد، از روی کد وضعیت پیام فارسی
 * می‌سازیم. مهم‌ترینش ۴۲۹ است: محدودیت تعداد ثبت، که هیچ‌وقت به‌شکل JSON
 * از CDN رد نمی‌شود.
 */

const BY_STATUS: Record<number, string> = {
  400: "اطلاعات واردشده کامل یا درست نیست.",
  404: "موردی که برایش نظر می‌نویسید پیدا نشد.",
  429: "تعداد نظرهای ثبت‌شده از این دستگاه زیاد است. کمی بعد دوباره تلاش کنید.",
};

export async function readFormError(res: Response, fallback: string): Promise<string> {
  try {
    const data = await res.json();
    if (data && typeof data.error === "string" && data.error) return data.error;
  } catch {
    // بدنه JSON نبود — پایین از روی کد وضعیت پیام می‌سازیم
  }
  return BY_STATUS[res.status] ?? (res.status >= 500 ? "خطای سرور. کمی بعد دوباره تلاش کنید." : fallback);
}
